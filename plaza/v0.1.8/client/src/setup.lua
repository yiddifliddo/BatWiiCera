-- BatWiiCera Plaza - self-install on Batocera (no terminal needed)
-- Version 0.1.8 | Author: yiddifliddo | Licence: MIT
--
-- The client runs with full rights on Batocera, so it can install itself:
-- copy this .love to /userdata/roms/plaza, write the Plaza system definition,
-- write the presence hook (executable), put the launcher script in roms/plaza
-- (the channel entry) and roms/ports, copy the bundled LÖVE runtime and the
-- channel artwork from the theme folder, drop the channel logo into any
-- installed BatWiiCera theme, then restart EmulationStation. The files it writes are embedded at build time
-- (src/embedded.lua, generated by build.sh from hook/ and installer/).

local embedded = require("src.embedded")

local M = {}

M.paths = {
  userdata = "/userdata",
  roms = "/userdata/roms/plaza",
  esCfgDir = "/userdata/system/configs/emulationstation",
  scripts = "/userdata/system/scripts",
  ports = "/userdata/roms/ports",
  themes = "/userdata/themes",
}

local function exists(path)
  local f = io.open(path, "r")
  if f then f:close(); return true end
  return false
end

local function dirExists(path)
  local ok = os.execute('[ -d "' .. path .. '" ]')
  return ok == 0 or ok == true
end

local function writeFile(path, data, executable)
  local f, err = io.open(path, "wb")
  if not f then return false, err end
  f:write(data)
  f:close()
  if executable then os.execute('chmod 755 "' .. path .. '"') end
  return true
end

local function copyFile(src, dst)
  local i, err = io.open(src, "rb")
  if not i then return false, err end
  local data = i:read("*a"); i:close()
  return writeFile(dst, data)
end

-- True when running on a Batocera-style system (has /userdata).
function M.isBatocera()
  return dirExists(M.paths.userdata)
end

-- What is already in place.
function M.status()
  return {
    system = exists(M.paths.esCfgDir .. "/es_systems_plaza.cfg"),
    hook = exists(M.paths.scripts .. "/batwiicera-plaza-presence.sh"),
    client = exists(M.paths.roms .. "/Plaza.love"),
    launcher = exists(M.paths.roms .. "/Plaza.sh"),
    runtime = (os.execute('ls "' .. M.paths.roms .. '"/runtime/love-*.AppImage >/dev/null 2>&1') == 0)
      or (os.execute('ls "' .. M.paths.roms .. '"/runtime/love-*.AppImage >/dev/null 2>&1') == true),
  }
end

function M.isInstalled()
  local s = M.status()
  return s.system and s.hook and s.client and s.launcher and s.runtime
end

-- Newest BatWiiCera theme copy that carries a _plaza folder, or nil.
function M.themePlazaDir()
  local p = io.popen('ls -td ' .. M.paths.themes .. '/*/_plaza 2>/dev/null')
  if not p then return nil end
  for dir in p:lines() do
    if exists(dir .. "/dist/BatWiiCera-Plaza.love") then p:close(); return dir end
  end
  p:close()
  return nil
end

-- Performs the install. Returns ok, list of messages.
function M.install()
  local log = {}
  local function note(m) log[#log + 1] = m end
  if not M.isBatocera() then return false, { "This is not a Batocera system (no /userdata)." } end

  os.execute('mkdir -p "' .. M.paths.roms .. '/runtime" "' .. M.paths.roms .. '/images" "' .. M.paths.esCfgDir .. '" "' .. M.paths.scripts .. '" "' .. M.paths.ports .. '"')

  -- 1. the client itself
  local src = love.filesystem.getSource()
  local ok, err
  if src and src:match("%.love$") and exists(src) then
    ok, err = copyFile(src, M.paths.roms .. "/Plaza.love")
    note(ok and "Copied the Plaza to roms/plaza" or ("Could not copy the Plaza: " .. tostring(err)))
  else
    ok = exists(M.paths.roms .. "/Plaza.love")
    note(ok and "Plaza already in roms/plaza" or "Running from a folder, not a .love file: copy BatWiiCera-Plaza.love to roms/plaza yourself")
  end
  writeFile(M.paths.roms .. "/gamelist.xml", embedded.gamelist)

  -- 2. the Plaza system for EmulationStation
  ok, err = writeFile(M.paths.esCfgDir .. "/es_systems_plaza.cfg", embedded.esSystems)
  note(ok and "Added the Plaza channel to EmulationStation" or ("Could not write the system file: " .. tostring(err)))

  -- 3. the presence hook (must be executable)
  ok, err = writeFile(M.paths.scripts .. "/batwiicera-plaza-presence.sh", embedded.hook, true)
  note(ok and "Installed the presence hook" or ("Could not write the hook: " .. tostring(err)))

  -- 4. the launcher: the channel's entry in roms/plaza, and the Ports entry
  ok, err = writeFile(M.paths.roms .. "/Plaza.sh", embedded.ports, true)
  note(ok and "Wrote the channel launcher" or ("Could not write the launcher: " .. tostring(err)))
  ok, err = writeFile(M.paths.ports .. "/Plaza.sh", embedded.ports, true)
  note(ok and "Added Plaza to the Ports list" or ("Could not write the Ports script: " .. tostring(err)))

  -- 5. the bundled runtime and the artwork come from the theme folder
  local src = M.themePlazaDir()
  if src then
    os.execute('cp "' .. src .. '"/runtime/love-*.AppImage "' .. M.paths.roms .. '/runtime/" 2>/dev/null; chmod +x "' .. M.paths.roms .. '"/runtime/*.AppImage 2>/dev/null')
    os.execute('cp "' .. src .. '"/installer/images/*.png "' .. M.paths.roms .. '/images/" 2>/dev/null')
    note("Copied the runtime and artwork from " .. (src:match("themes/([^/]+)/") or "the theme"))
  else
    note("No BatWiiCera theme with a _plaza folder found; runtime not copied (install the theme 0.1.17 or newer)")
  end

  -- 6. channel logo for installed BatWiiCera theme copies that predate 0.1.11
  local p = io.popen('ls -d ' .. M.paths.themes .. '/BatWiiCera*/_inc/systems/logos 2>/dev/null')
  if p then
    for dir in p:lines() do
      if not exists(dir .. "/plaza.svg") then
        writeFile(dir .. "/plaza.svg", embedded.logo)
        note("Added the channel logo to " .. dir:match("themes/([^/]+)/"))
      end
    end
    p:close()
  end

  local st = M.status()
  local good = st.system and st.hook and st.launcher
  if good and not st.runtime then note("Warning: no runtime in roms/plaza/runtime; the channel will not start until the theme is installed") end
  note(good and "Done. EmulationStation restarts in a moment; the Plaza channel will be on the console grid." or "Install incomplete, see above.")
  return good, log
end

-- Restarts EmulationStation a few seconds from now, detached from this
-- process, so the client can quit cleanly first. Batocera supervises
-- EmulationStation and brings it back with the new system list.
function M.restartEmulationStation()
  if not M.isBatocera() then return false end
  local cmd = "sleep 3; batocera-es-swissknife --restart"
  local wrap = "nohup setsid bash -c '" .. cmd .. "' >/dev/null 2>&1 </dev/null &"
  local ok = os.execute("command -v setsid >/dev/null 2>&1")
  if not (ok == 0 or ok == true) then
    wrap = "nohup bash -c '" .. cmd .. "' >/dev/null 2>&1 </dev/null &"
  end
  os.execute(wrap)
  return true
end

-- Removes what install() wrote (keeps the player's profile).
function M.uninstall()
  os.remove(M.paths.esCfgDir .. "/es_systems_plaza.cfg")
  os.remove(M.paths.scripts .. "/batwiicera-plaza-presence.sh")
  os.remove(M.paths.roms .. "/gamelist.xml")
  os.remove(M.paths.roms .. "/Plaza.love")
  os.remove(M.paths.ports .. "/Plaza.sh")
  os.remove(M.paths.roms .. "/Plaza.sh")
  return true
end

return M
